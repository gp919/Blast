using UnityEngine;

namespace Blast.Core
{
    // 계층: Core. 한 틱이 끝난 시점의 플레이어 시뮬레이션 상태 전체입니다.
    //
    // 이 구조체의 계약은 한 문장입니다.
    //   틱 N 의 상태를 복원하고 틱 N 이후의 입력을 그대로 재생하면
    //   원래와 동일한 결과가 나와야 한다.
    // 필드를 추가할지 말지 헷갈리면 "저장하지 않으면 재시뮬레이션이 갈라지는가"를
    // 물어보세요. 갈라지면 상태이고, 아니면 파생값이라 여기 넣지 않습니다.
    //
    // class 가 아니라 struct 인 이유는 세 가지입니다.
    //   1. 복원이 대입 한 줄로 끝납니다
    //   2. 링버퍼가 배열 하나라 틱마다 힙 할당이 없습니다
    //   3. blittable 이라 직렬화가 단순해집니다
    //
    // 주의: 링버퍼는 반드시 배열로 만드세요. List<T> 의 인덱서는 복사본을 돌려주므로
    // buffer[i].Position = x 가 컴파일되지 않습니다. 배열은 제자리 수정이 됩니다.
    public struct PlayerState
    {
        // 이 상태가 어느 틱의 결과인지입니다. 검증 전용 필드입니다.
        //
        // 링버퍼에서 tick 을 마스킹해 꺼낸 슬롯이 정말 그 틱인지 확인할 방법이 없으면
        // 되감기 시작 오프셋이나 인덱싱 off-by-one 이 조용히 통과합니다.
        // 꺼낼 때마다 이 값을 기대 틱과 대조하면 즉시 터집니다.
        //
        // 전송 시에는 이 필드를 뺍니다. 스냅샷 헤더에 틱이 이미 들어가므로
        // 플레이어마다 반복해서 보낼 이유가 없습니다. 메모리 표현과 와이어 표현은 별개입니다.
        public uint Tick;

        public Vector2 Position;
        public Vector2 Velocity;

        // 틱 시작 시점의 점프 가능 여부 판단에 쓰입니다.
        // 위치에서 매번 다시 캐스트해 구할 수도 있지만, 1비트 아끼자고
        // 틱마다 BoxCast 를 한 번 더 돌릴 이유가 없어 상태로 들고 갑니다.
        public bool IsGrounded;

        // 지면에서 벗어난 뒤에도 점프를 허용하는 남은 틱 수입니다.
        // 틱을 넘어 유지되고 점프 성립 여부를 바꾸므로 명백한 상태입니다.
        public byte CoyoteTicksRemaining;

        // -1 또는 1. 입력이 0 인 동안에도 유지되므로 파생값이 아닙니다.
        // 근접 공격의 방향을 결정하므로 Presentation 이 아니라 Simulation 소관입니다.
        public sbyte FacingDirection;
    }
}
